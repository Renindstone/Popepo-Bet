    """Hasta ahora contaban todas las que fueron apuesta del día (el 30-10, cuatro). Se queda una por día: la de más
    valor por confianza (valor anunciado × última confianza; la de cuando se eligió no se guardaba) entre las que se
    anunciaron ese mismo día. Las calculadas la víspera solo cuentan si ese día no hubo otra; los días que aún no llegan
    se quedan sin ninguna hasta que lleguen. Una retirada ya no queda marcada como la que se enseña."""
    tz = ZoneInfo("America/Lima")
    today = datetime.now(tz).date()
    conn = op.get_bind()
    conn.execute(sa.text("UPDATE pick SET is_pick_of_day = false WHERE status = 'withdrawn'"))
    rows = conn.execute(sa.text(
        "SELECT id, pick_date, coalesce(announced_at, created_at) AS at, coalesce(announced_ev, ev) AS ev, confidence "
        "FROM pick WHERE was_pick_of_day")).all()
    by_day = defaultdict(list)
    for r in rows:
        by_day[r.pick_date].append(r)
    for day, picks in by_day.items():
        same_day = [r for r in picks if r.at.astimezone(tz).date() >= day]
        eligible = [] if day > today else same_day or picks
        best = max(eligible, key=lambda r: r.ev * r.confidence, default=None)
        for r in picks:
            conn.execute(sa.text("UPDATE pick SET was_pick_of_day = :w, pod_score = :sc WHERE id = :id"),
                         {"w": r is best, "sc": r.ev * r.confidence if r in eligible else None, "id": r.id})


